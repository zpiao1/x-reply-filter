import type { BenchmarkCase, DomMetaFallback, GraphqlTweetMeta } from "./dataset-humans.ts";

const BASE_TS = Date.parse("2026-11-18T12:00:00Z");
const DAY_MS = 24 * 3600 * 1000;

interface BotInput {
  id: string;
  threadId?: string;
  lang: "en" | "zh-hans" | "zh-hant" | "ja";
  opText: string;
  opAuthorId: string;
  replyText: string;
  replyAuthorId: string;
  category: string;
  delaySec?: number;
  blue?: boolean;
  verifiedType?: "blue" | "business" | "government" | "none";
  following?: boolean;
  followedBy?: boolean;
  bio?: string;
  displayName?: string;
  followers?: number;
  friends?: number;
  statuses?: number;
  accountAgeDays?: number;
  defaultPfp?: boolean;
  likes?: number;
  opLikes?: number;
  replies?: number;
  retweets?: number;
  media?: Array<"photo" | "video" | "animated_gif">;
  hasExternalLink?: boolean;
  hasQuote?: boolean;
  domOnly?: boolean;
}

const REALISTIC_BOT_NEUTRAL_BIOS: ReadonlyArray<string> = [
  "Tech, software, and product design.",
  "Writing about markets, startups, and culture.",
  "Curious mind. Books, coffee, and internet things.",
  "",
  "Engineer & writer based in Austin.",
  "News, tech, and everyday observations.",
  "关注科技、商业与效率工具。",
  "テクノロジーと日々のメモ。",
];

function makeBot(idx: number, c: BotInput): BenchmarkCase {
  const opTs = BASE_TS - (idx + 120) * 1800_000;
  const delaySec = c.delaySec ?? 12 + ((idx * 41) % 900);
  const threadId = c.threadId ?? `19900000000000${String(300 + idx).padStart(3, "0")}`;
  const isBlue = c.blue ?? true;
  const vType = c.verifiedType ?? (isBlue ? "blue" : "none");
  const media = c.media ?? [];
  // Realistic overlapping X distributions: aged/hijacked or real-account reply-bots (60% > 1yr),
  // some bots have solid follower counts and engagement-pod likes, and neutral bios unless explicitly promo.
  const ageDays =
    c.accountAgeDays ??
    (idx % 5 < 2 ? 45 + ((idx * 53) % 320) : 420 + ((idx * 149) % 2400));
  const followers =
    c.followers ??
    (idx % 3 === 0 ? 1500 + ((idx * 389) % 18000) : 110 + ((idx * 167) % 1400));
  const friends =
    c.friends ??
    (idx % 3 === 0 ? 350 + ((idx * 127) % 1400) : 520 + ((idx * 251) % 3400));
  const dailyRate = 1.5 + ((idx * 19) % 34);
  const statuses = c.statuses ?? Math.max(120, Math.round(ageDays * dailyRate));
  const likes =
    c.likes ??
    (idx % 4 === 0 ? 3 + ((idx * 5) % 12) : idx % 3);
  const domMeta: DomMetaFallback = {
    hasVerifiedBadge: isBlue || vType !== "none",
    hasPrimaryMedia: media.length > 0,
    hasExternalLink: c.hasExternalLink ?? false,
    hasQuote: c.hasQuote ?? false,
  };
  const graphqlMeta: GraphqlTweetMeta | null = c.domOnly
    ? null
    : {
        tweetCreatedAtMs: opTs + delaySec * 1000,
        inReplyToStatusId: threadId,
        conversationId: threadId,
        favoriteCount: likes,
        opFavoriteCount: c.opLikes ?? 500 + ((idx * 227) % 6000),
        replyCount: c.replies ?? (idx % 2),
        retweetCount: c.retweets ?? (idx % 2),
        mediaTypes: media,
        displayName: c.displayName ?? c.replyAuthorId,
        authorCreatedAtMs: BASE_TS - ageDays * DAY_MS,
        description: c.bio ?? REALISTIC_BOT_NEUTRAL_BIOS[idx % REALISTIC_BOT_NEUTRAL_BIOS.length]!,
        isBlueVerified: isBlue,
        verifiedType: vType,
        following: c.following ?? false,
        followedBy: c.followedBy ?? false,
        followersCount: followers,
        friendsCount: friends,
        statusesCount: statuses,
        defaultProfileImage: c.defaultPfp ?? false,
      };
  return {
    id: c.id,
    threadId,
    lang: c.lang,
    opText: c.opText,
    opAuthorId: c.opAuthorId,
    opCreatedAtMs: opTs,
    replyText: c.replyText,
    replyAuthorId: c.replyAuthorId,
    isOpFollowup: false,
    expectedLabel: "bot",
    category: c.category,
    domMeta,
    graphqlMeta,
  };
}

